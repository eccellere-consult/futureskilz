import { SOURCE_PLAIN, confidenceLabel, type Passport } from "./model";

const fmt = (iso: string) => new Date(iso).toLocaleDateString("en-IN", { day: "numeric", month: "long", year: "numeric" });

/**
 * The passport as a document: the same on the owner's screen, in a shared link and on paper. It says where each level came from, and
 * what it is not: a record of what someone has shown so far, not a certificate or a test result.
 */
export function PassportDocument({ passport, sharedUntil }: { passport: Passport; sharedUntil?: string }) {
  const families = [...new Set(passport.skills.map((skill) => skill.family))];
  const { basis } = passport;
  return (
    <article aria-label="Skill Passport" className="mx-auto w-full max-w-4xl border border-border bg-surface px-6 py-8 sm:px-10 sm:py-10 print:border-0 print:p-0">
      <p className="font-mono text-[10px] uppercase text-gold">FutureSkilz · Skill Passport</p>
      <h1 className="mt-2 font-serif text-4xl leading-tight sm:text-5xl">{passport.name}</h1>
      <p className="mt-2 text-ink-mid">
        {passport.currentRole ? `${passport.currentRole}` : ""}
        {passport.currentRole && passport.targetRole ? " · working toward " : passport.targetRole ? "Working toward " : ""}
        {passport.targetRole ?? ""}
      </p>
      <p className="mt-1 text-xs text-ink-light">As of {fmt(passport.generatedAt)}{sharedUntil ? ` · this link works until ${fmt(sharedUntil)}` : ""}</p>

      <section aria-label="How to read this" className="mt-6 border-l-2 border-gold bg-gold-pale/50 p-4 text-sm leading-6">
        <p className="font-semibold">How to read this</p>
        <p className="mt-1 text-ink-mid">Levels run from 0 to 5. Each says what backs it: a person&apos;s own rating, situations they described, or a lesson they completed with a correct check. Of {passport.skills.length} skills shown, {basis.completedLessons} are backed by completed lessons, {basis.described} by situations described, and {basis.selfRatingOnly} by a self-rating alone.{basis.inferredNotListed ? ` ${basis.inferredNotListed} further skill${basis.inferredNotListed === 1 ? " is" : "s are"} only guessed from related answers, so ${basis.inferredNotListed === 1 ? "it is" : "they are"} not listed.` : ""} This is a record of what has been shown so far. It is not a certificate or a test result.</p>
      </section>

      {passport.skills.length === 0 ? <p className="mt-8 text-ink-mid">No skills have been assessed yet.</p> : null}
      {families.map((family) => (
        <section aria-label={family} className="mt-8" key={family}>
          <h2 className="font-display text-2xl">{family}</h2>
          <table className="mt-3 w-full border-collapse text-left text-sm">
            <thead><tr className="border-b border-border font-mono text-[10px] uppercase text-ink-light"><th className="py-2 pr-3">Skill</th><th className="py-2 pr-3">Level</th><th className="py-2 pr-3">Confidence</th><th className="py-2">Backed by</th></tr></thead>
            <tbody>
              {passport.skills.filter((skill) => skill.family === family).map((skill) => (
                <tr className="border-b border-border align-top" key={skill.skill}>
                  <td className="py-2 pr-3 font-medium">{skill.name}</td>
                  <td className="py-2 pr-3"><span className="font-mono">{skill.level.toFixed(1)}</span><span aria-hidden="true" className="mt-1 block h-1.5 w-24 bg-border"><span className="block h-1.5 bg-gold" style={{ width: `${(skill.level / 5) * 100}%` }} /></span></td>
                  <td className="py-2 pr-3">{confidenceLabel(skill.confidence)}</td>
                  <td className="py-2 text-ink-mid">{SOURCE_PLAIN[skill.source]}{skill.withResult ? ", with a result described" : ""}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </section>
      ))}

      {passport.evidence.length ? (
        <section aria-label="Evidence" className="mt-10">
          <h2 className="font-display text-2xl">What has been completed</h2>
          <ul className="mt-3 divide-y divide-border border-y border-border text-sm">
            {passport.evidence.map((item) => <li className="flex flex-wrap justify-between gap-2 py-2" key={`${item.title}-${item.date}`}><span>{item.title}</span><span className="text-ink-light">{fmt(item.date)}</span></li>)}
          </ul>
        </section>
      ) : null}

      <p className="mt-10 border-t border-border pt-4 text-xs leading-5 text-ink-light">Generated by FutureSkilz. Levels are estimates and can change. Practice notes, goals and conversations are never part of a passport.</p>
    </article>
  );
}
